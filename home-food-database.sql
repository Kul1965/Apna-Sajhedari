-- Home Made Food ordering module for Apna-Sajhedari rebrand
-- Safe additive migration: does not drop or alter existing Sajhedari tables.
-- Run in Supabase SQL Editor after confirming public.is_admin() exists.

create extension if not exists pgcrypto;

create table if not exists public.food_menu_items (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text,
  category text not null default 'Meals',
  price numeric(12,2) not null check (price >= 0),
  image_url text,
  available boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.food_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  member_id uuid references public.members(id) on delete set null,
  customer_user_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null,
  phone text,
  delivery_address text not null,
  notes text,
  subtotal numeric(12,2) not null check (subtotal >= 0),
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  total_amount numeric(12,2) not null check (total_amount >= 0),
  status text not null default 'pending'
    check (status in ('pending','accepted','preparing','ready','out_for_delivery','delivered','cancelled')),
  payment_status text not null default 'pending'
    check (payment_status in ('pending','proof_submitted','paid','rejected','refunded')),
  payment_qr_id uuid,
  payment_reference text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.food_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.food_orders(id) on delete cascade,
  menu_item_id uuid references public.food_menu_items(id) on delete set null,
  item_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);

create table if not exists public.food_payment_qrs (
  id uuid primary key default gen_random_uuid(),
  label text not null,
  upi_id text,
  account_name text,
  qr_image_url text not null,
  active boolean not null default true,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.food_orders
  add constraint food_orders_payment_qr_fk
  foreign key (payment_qr_id) references public.food_payment_qrs(id) on delete set null;

create table if not exists public.food_payment_proofs (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.food_orders(id) on delete cascade,
  customer_user_id uuid not null references auth.users(id) on delete restrict,
  proof_image_url text,
  transaction_reference text,
  amount_claimed numeric(12,2) not null check (amount_claimed >= 0),
  status text not null default 'submitted' check (status in ('submitted','approved','rejected')),
  admin_note text,
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists food_orders_customer_created_idx
  on public.food_orders(customer_user_id, created_at desc);
create index if not exists food_orders_status_created_idx
  on public.food_orders(status, created_at desc);
create index if not exists food_order_items_order_idx on public.food_order_items(order_id);
create index if not exists food_payment_proofs_order_idx on public.food_payment_proofs(order_id);

alter table public.food_menu_items enable row level security;
alter table public.food_orders enable row level security;
alter table public.food_order_items enable row level security;
alter table public.food_payment_qrs enable row level security;
alter table public.food_payment_proofs enable row level security;

drop policy if exists "food menu public reads available" on public.food_menu_items;
create policy "food menu public reads available" on public.food_menu_items
for select to anon, authenticated using (available or public.is_admin());
drop policy if exists "food menu admin manages" on public.food_menu_items;
create policy "food menu admin manages" on public.food_menu_items
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "food orders customer or admin reads" on public.food_orders;
create policy "food orders customer or admin reads" on public.food_orders
for select to authenticated using (customer_user_id = auth.uid() or public.is_admin());
drop policy if exists "food orders customer creates own" on public.food_orders;
create policy "food orders customer creates own" on public.food_orders
for insert to authenticated with check (customer_user_id = auth.uid() and payment_status = 'pending' and status = 'pending');
drop policy if exists "food orders admin updates" on public.food_orders;
create policy "food orders admin updates" on public.food_orders
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "food order items customer or admin reads" on public.food_order_items;
create policy "food order items customer or admin reads" on public.food_order_items
for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.food_orders o
    where o.id = food_order_items.order_id and o.customer_user_id = auth.uid()
  )
);
drop policy if exists "food order items customer creates own order" on public.food_order_items;
create policy "food order items customer creates own order" on public.food_order_items
for insert to authenticated with check (
  exists (select 1 from public.food_orders o
    where o.id = food_order_items.order_id and o.customer_user_id = auth.uid())
);
drop policy if exists "food order items admin manages" on public.food_order_items;
create policy "food order items admin manages" on public.food_order_items
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "active payment qrs visible" on public.food_payment_qrs;
create policy "active payment qrs visible" on public.food_payment_qrs
for select to anon, authenticated using (active or public.is_admin());
drop policy if exists "admin manages payment qrs" on public.food_payment_qrs;
create policy "admin manages payment qrs" on public.food_payment_qrs
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "customer or admin reads payment proofs" on public.food_payment_proofs;
create policy "customer or admin reads payment proofs" on public.food_payment_proofs
for select to authenticated using (customer_user_id = auth.uid() or public.is_admin());
drop policy if exists "customer submits own payment proof" on public.food_payment_proofs;
create policy "customer submits own payment proof" on public.food_payment_proofs
for insert to authenticated with check (
  customer_user_id = auth.uid() and status = 'submitted' and exists (
    select 1 from public.food_orders o
    where o.id = food_payment_proofs.order_id and o.customer_user_id = auth.uid()
  )
);
drop policy if exists "admin reviews payment proofs" on public.food_payment_proofs;
create policy "admin reviews payment proofs" on public.food_payment_proofs
for update to authenticated using (public.is_admin()) with check (public.is_admin());

grant select on public.food_menu_items, public.food_payment_qrs to anon, authenticated;
grant select, insert on public.food_orders, public.food_order_items, public.food_payment_proofs to authenticated;
grant update on public.food_orders, public.food_payment_proofs to authenticated;
grant all on public.food_menu_items, public.food_orders, public.food_order_items, public.food_payment_qrs, public.food_payment_proofs to authenticated;

-- Admin accounts are identified by the existing public.is_admin() function.
-- QR image files should be stored in a private Supabase Storage bucket; expose only active QR images.
-- Client-side totals are for display; production order creation should validate prices/totals server-side.
