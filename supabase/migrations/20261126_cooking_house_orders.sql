-- Cooking House recipe ordering (additive; preserves existing food orders and data)
alter table public.food_recipes
  add column if not exists image_url text,
  add column if not exists price numeric(12,2) not null default 0 check (price >= 0),
  add column if not exists available boolean not null default true;

create table if not exists public.recipe_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_user_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  customer_phone text not null default '',
  delivery_address text not null default '',
  notes text not null default '',
  status text not null default 'pending' check (status in ('pending','accepted','preparing','ready','delivered','cancelled')),
  total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.recipe_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.recipe_orders(id) on delete cascade,
  recipe_id uuid references public.food_recipes(id) on delete set null,
  recipe_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);
alter table public.recipe_orders enable row level security;
alter table public.recipe_order_items enable row level security;
drop policy if exists "members read own recipe orders admins read all" on public.recipe_orders;
create policy "members read own recipe orders admins read all" on public.recipe_orders
for select to authenticated using (customer_user_id=auth.uid() or exists(select 1 from public.food_admins a where a.user_id=auth.uid()));
drop policy if exists "members create own recipe orders" on public.recipe_orders;
create policy "members create own recipe orders" on public.recipe_orders
for insert to authenticated with check (customer_user_id=auth.uid());
drop policy if exists "food admins update recipe orders" on public.recipe_orders;
create policy "food admins update recipe orders" on public.recipe_orders
for update to authenticated using (exists(select 1 from public.food_admins a where a.user_id=auth.uid()))
with check (exists(select 1 from public.food_admins a where a.user_id=auth.uid()));
drop policy if exists "read own recipe order items or admin" on public.recipe_order_items;
create policy "read own recipe order items or admin" on public.recipe_order_items
for select to authenticated using (exists(select 1 from public.recipe_orders o where o.id=order_id and (o.customer_user_id=auth.uid() or exists(select 1 from public.food_admins a where a.user_id=auth.uid()))));
drop policy if exists "members add items to own recipe orders" on public.recipe_order_items;
create policy "members add items to own recipe orders" on public.recipe_order_items
for insert to authenticated with check (exists(select 1 from public.recipe_orders o where o.id=order_id and o.customer_user_id=auth.uid()));
drop policy if exists "food admins manage recipes" on public.food_recipes;
create policy "food admins manage recipes" on public.food_recipes for all to authenticated
using (exists(select 1 from public.food_admins a where a.user_id=auth.uid()))
with check (exists(select 1 from public.food_admins a where a.user_id=auth.uid()));
drop policy if exists "authenticated can read recipes" on public.food_recipes;
create policy "authenticated can read recipes" on public.food_recipes for select to authenticated using (true);
grant select, insert on public.recipe_orders to authenticated;
grant select, insert on public.recipe_order_items to authenticated;
grant update on public.recipe_orders to authenticated;
grant select, insert, update, delete on public.food_recipes to authenticated;
create index if not exists idx_recipe_orders_customer_date on public.recipe_orders(customer_user_id,created_at desc);
create index if not exists idx_recipe_order_items_order on public.recipe_order_items(order_id);
